class BehaviorProfile(Base, IDMixin, StampMixin):
    """Posting-behavior profile per actor/handle — DATABASE.md §8."""

    __tablename__ = "behavior_profiles"

    actor_id: Mapped[str] = mapped_column(
        ForeignKey("actors.id", ondelete="CASCADE"), nullable=False
    )
    handle_id: Mapped[Optional[str]] = mapped_column(
        ForeignKey("handles.id", ondelete="SET NULL")
    )
    frequency_mean: Mapped[Optional[float]] = mapped_column(Numeric(10, 4))
    interval_mean: Mapped[Optional[Any]] = mapped_column(Interval)
    # Numeric[] in the DDL; JSON arrays keep SQLite parity (flagged drift).
