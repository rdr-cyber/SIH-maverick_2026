class Post(Base, IDMixin, SeenMixin, StampMixin):
    """A forum/marketplace post (feeds stylometry) — DATABASE.md §5."""

    __tablename__ = "posts"

    external_id: Mapped[str] = mapped_column(Text, nullable=False)
    # forums.id or marketplaces.id — polymorphic per DDL, no single FK.
    platform_id: Mapped[str] = mapped_column(GUID(), nullable=False)
    platform_type: Mapped[str] = mapped_column(String(20), nullable=False)
    author_handle_id: Mapped[Optional[str]] = mapped_column(
        ForeignKey("handles.id", ondelete="SET NULL")
    )
    author_raw: Mapped[Optional[str]] = mapped_column(Text)
    title: Mapped[Optional[str]] = mapped_column(Text)
    body: Mapped[Optional[str]] = mapped_column(Text)
    posted_at: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    language: Mapped[str] = mapped_column(String(10), nullable=False, default="en")
    site: Mapped[Optional[str]] = mapped_column(Text)
    source_id: Mapped[str] = mapped_column(
        ForeignKey("sources.id", ondelete="RESTRICT"), nullable=False
    )
    metadata_json: Mapped[dict[str, Any]] = mapped_column(
        "metadata", JSONBVariant, nullable=False, default=dict
    )

    author_handle: Mapped[Optional["Handle"]] = relationship()

    __table_args__ = (
        CheckConstraint(
            "platform_type IN ('marketplace', 'forum')", name="ck_posts_platform_type"
        ),
        UniqueConstraint("source_id", "platform_id", "external_id", name="uq_posts_external"),
        Index("idx_posts_handle", "author_handle_id"),
        Index("idx_posts_posted", "posted_at"),
    )


