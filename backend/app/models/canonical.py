class Handle(Base, IDMixin, SeenMixin, StampMixin):
    """A platform handle as observed on a source. Deduped on normalized_key."""

    __tablename__ = "handles"

    source_id: Mapped[str] = mapped_column(
        ForeignKey("sources.id", ondelete="RESTRICT"), nullable=False
    )
    value: Mapped[str] = mapped_column(Text, nullable=False)
    normalized: Mapped[str] = mapped_column(Text, nullable=False)
    normalized_key: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    # Resolved at ingest to forums.id or marketplaces.id — polymorphic, so no
    # single FK (smallest consistent reading of DATABASE.md §3 handles).
    platform_id: Mapped[Optional[str]] = mapped_column(GUID())
    platform_type: Mapped[Optional[str]] = mapped_column(String(20))
    category: Mapped[str] = mapped_column(
        String(20), nullable=False, default="other"
    )
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="active")

    source: Mapped["Source"] = relationship(lazy="joined")  # type: ignore[name-defined]  # noqa: F821

    __table_args__ = (
        CheckConstraint(
            "platform_type IN ('marketplace', 'forum') OR platform_type IS NULL",
            name="ck_handles_platform_type",
        ),
        CheckConstraint(
            "category IN ('marketplace', 'forum', 'paste', 'other')",
            name="ck_handles_category",
        ),
        CheckConstraint("status IN ('active', 'inactive')", name="ck_handles_status"),
        Index("idx_handles_platform", "platform_id"),
    )


