    migrations: Mapped[list[Any]] = mapped_column(JSONBVariant, nullable=False, default=list)
    raw_vector: Mapped[dict[str, Any]] = mapped_column(JSONBVariant, nullable=False, default=dict)
    source_id: Mapped[Optional[str]] = mapped_column(ForeignKey("sources.id"))
    computed_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime, server_default=func.now()
    )
    metadata_json: Mapped[dict[str, Any]] = mapped_column(
        "metadata", JSONBVariant, nullable=False, default=dict
    )

    __table_args__ = (Index("idx_behavior_actor", "actor_id"),)


