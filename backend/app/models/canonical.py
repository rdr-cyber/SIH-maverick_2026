"""Canonical identity, infrastructure & content entities — DATABASE.md §3–§7.

These tables complete the canonical schema (``docs/schemas/postgres_schema.sql``)
alongside the prototype's ``actors``/``personas``/``identifiers`` (identity.py).
They are populated from Phase 3 (ingestion) onward; the models exist from day
one so migrations and the ingestion boundary match DATABASE.md exactly.

Conventions (DATABASE.md §1):
- UUID PKs generated by the app.
- ``normalized_key`` is the canonical dedup key, globally unique per table.
- ``metadata`` JSONB flexible fields; TIMESTAMPTZ-equivalent naive-UTC here.
- No hard deletes for intelligence data: ``status`` soft-delete columns.

Column semantics stay engine-agnostic: GUID → UUID on PostgreSQL / CHAR(36) on
SQLite; JSONBVariant → JSONB / JSON. The same models serve both modes.
"""
